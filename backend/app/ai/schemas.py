"""Pydantic schemas for AI reasoning, structured tool calling, and conversation messaging."""

from datetime import datetime
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field

from app.desktop.schemas import VerificationStatus


class MessageRole(str, Enum):
    """Standard message roles in LLM conversations."""
    SYSTEM = "system"
    USER = "user"
    ASSISTANT = "assistant"
    TOOL = "tool"


class ResponseType(str, Enum):
    """Normalized response classifications."""
    CONVERSATIONAL = "conversational"
    PROPOSED_TOOL_CALL = "proposed_tool_call"
    TOOL_RESULT = "tool_result"
    CLARIFICATION = "clarification"
    ERROR = "error"


class ChatMessage(BaseModel):
    """Represents a validated message in a conversation thread."""
    role: MessageRole
    content: Optional[str] = Field(default=None, max_length=10000, description="Message text content")
    name: Optional[str] = Field(default=None, description="Tool name if role is tool")
    tool_call_id: Optional[str] = Field(default=None, description="Tool call ID for tool outputs")
    tool_calls: Optional[List[Dict[str, Any]]] = Field(default=None, description="Tool calls generated by assistant")


class ToolCall(BaseModel):
    """Structured tool invocation proposed by the AI reasoning layer."""
    call_id: str
    tool_name: str
    arguments: Dict[str, Any] = Field(default_factory=dict)
    purpose: Optional[str] = None


class ToolResult(BaseModel):
    """Normalized output produced by executing an approved tool."""
    call_id: str
    tool_name: str
    status: str
    result: Any
    error_code: Optional[str] = None
    safe_error_message: Optional[str] = None
    verification_status: VerificationStatus = VerificationStatus.UNVERIFIED


class AssistantResponse(BaseModel):
    """Normalized output returned by AI reasoning service to clients."""
    response_id: str
    conversation_id: str
    message: str
    response_type: ResponseType
    tool_calls: List[ToolCall] = Field(default_factory=list)
    tool_results: List[ToolResult] = Field(default_factory=list)
    requires_clarification: bool = False
    usage_metadata: Optional[Dict[str, Any]] = None
    provider_metadata: Optional[Dict[str, Any]] = None
    created_at: datetime

    model_config = ConfigDict(from_attributes=True)


class ChatRequest(BaseModel):
    """API payload for user chat requests."""
    message: str = Field(..., min_length=1, max_length=4000, description="User instruction or prompt")
    conversation_id: Optional[str] = Field(default=None, description="Optional conversation context identifier")


class AssistantStatusResponse(BaseModel):
    """Diagnostic status report of the AI reasoning layer."""
    provider: str
    model: str
    is_configured: bool
    tools_available_count: int
    tools_registered: List[str]
    max_tool_rounds: int
